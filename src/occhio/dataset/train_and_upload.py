"""
Train Models on HuggingFace Samples & Upload Weights.

For each distribution in the HF repo:
1. Download samples.safetensors from HuggingFace
2. Train a TiedLinearRelu autoencoder on those exact samples
3. Upload weights.safetensors + weights.json to HuggingFace

This ensures the model is trained on the SAME samples that are published,
so anyone can reproduce the exact embedding space.

Samples must already exist on HF — see upload_samples.py.
"""

import json
import shutil
import tempfile
from pathlib import Path

import torch
from huggingface_hub import HfApi, hf_hub_download
from safetensors.torch import load_file

from occhio.autoencoder import TiedLinearRelu
from occhio.toy_model import ToyModel

# --- Constants ---
N_HIDDEN = 200
N_EPOCHS = 30_000
BATCH_SIZE = 1024
LEARNING_RATE = 3e-4
WEIGHT_DECAY = 0.05
DEVICE = "mps"

AE_SEED = 0  # torch.Generator seed for autoencoder weight init

DATASET_REPO = "kaushikreddyxyz/occhio-distributions"
MODEL_REPO = "kaushikreddyxyz/occhio-models"
BRANDING = (
    "Generated by occhio — a research library for building and studying toy models. "
    "https://occhio.dev/ | Docs: https://docs.occhio.dev"
)

DISTRIBUTIONS = [
    "sparse_uniform",
    "correlated_pairs",
    "hierarchical_pairs",
    "power_law_digraph",
    "dag_random_walk",
    "simplicial_complex",
    "spherical",
    "torus",
]

# --- Auth ---
HF_TOKEN = input("HuggingFace token: ")
api = HfApi(token=HF_TOKEN)
api.create_repo(MODEL_REPO, exist_ok=True)


def train_and_upload(name: str) -> None:
    """Download samples from HF, train TiedLinearRelu, upload weights."""
    print(f"\n{'=' * 60}")
    print(f"  {name} — training")
    print(f"{'=' * 60}")

    # 1. Download samples from dataset repo
    samples_path = hf_hub_download(
        DATASET_REPO,
        f"{name}/samples/samples.safetensors",
        repo_type="dataset",
    )
    samples_json_path = hf_hub_download(
        DATASET_REPO,
        f"{name}/samples/samples.json",
        repo_type="dataset",
    )

    # Sanity check
    data = load_file(samples_path)
    samples = data["samples"]
    n_samples, n_feat = samples.shape
    nan_count = samples.isnan().sum().item()
    nonzero_rows = (samples.sum(dim=-1) != 0).sum().item()
    print(
        f"  samples: {list(samples.shape)}, NaN: {nan_count}, nonzero: {nonzero_rows}/{n_samples}"
    )
    del samples, data

    if nan_count > 0 or nonzero_rows == 0:
        print("  *** CORRUPT SAMPLES — skipping ***")
        return

    # Read description from samples.json
    samples_meta = json.loads(Path(samples_json_path).read_text())
    description = samples_meta.get("description", "")

    # 2. Train
    ae_gen = torch.Generator(DEVICE)
    ae_gen.manual_seed(AE_SEED)
    ae = TiedLinearRelu(n_feat, N_HIDDEN, device=DEVICE, generator=ae_gen)

    # ToyModel needs a distribution, but we use precomputed_data so it's never sampled.
    # Pass a dummy — any distribution with matching n_features works.
    from occhio.distributions import SparseUniform

    dummy_dist = SparseUniform(n_features=n_feat, p_active=0.01, device=DEVICE)
    tm = ToyModel(distribution=dummy_dist, ae=ae, device=DEVICE)
    tm.fit(
        N_EPOCHS,
        BATCH_SIZE,
        learning_rate=LEARNING_RATE,
        weight_decay=WEIGHT_DECAY,
        verbose=True,
        precomputed_data=samples_path,
    )

    # 3. Save & upload weights
    tmp = Path(tempfile.mkdtemp())
    try:
        weights_st = tmp / "weights.safetensors"
        ae.save_weights(weights_st)

        # Augment weights.json
        weights_json = json.loads((tmp / "weights.json").read_text())
        augmented = {
            "occhio": BRANDING,
            "description": description,
            "n_features": n_feat,
            "n_hidden": N_HIDDEN,
            "training": {
                "n_epochs": N_EPOCHS,
                "batch_size": BATCH_SIZE,
                "learning_rate": LEARNING_RATE,
                "weight_decay": WEIGHT_DECAY,
                "trained_on_precomputed_samples": True,
                "n_training_samples": n_samples,
                "autoencoder_generator": {
                    "seed": AE_SEED,
                    "device": DEVICE,
                    "note": "Controls weight initialization of TiedLinearRelu",
                },
            },
            **weights_json,
        }
        (tmp / "weights.json").write_text(json.dumps(augmented, indent=2) + "\n")

        for suffix in (".safetensors", ".json"):
            local = tmp / f"weights{suffix}"
            remote = f"{name}/weights/weights{suffix}"
            api.upload_file(
                path_or_fileobj=str(local),
                path_in_repo=remote,
                repo_id=MODEL_REPO,
                repo_type="model",
            )
            print(f"  uploaded {remote}")
    finally:
        shutil.rmtree(tmp)

    print(f"  done: {name}\n")


# %%
for dist_name in DISTRIBUTIONS:
    train_and_upload(dist_name)

