"""
Generate & Upload Sample Datasets to HuggingFace.

For each distribution defined in distribution_list.txt:
1. Create the distribution (N=1296 features, 6^4 for torus compatibility)
2. Sample 100K points in chunks (CPU-saved to avoid MPS corruption)
3. Upload samples.safetensors + samples.json to HuggingFace

Run cell 0 to authenticate and define helpers,
then run distribution cells individually or all at once.

Weights are trained separately — see train_and_upload.py.
"""

import json
import math
import random
import shutil
import tempfile
from pathlib import Path

import torch
from huggingface_hub import HfApi
from safetensors.torch import save_file

from occhio.distributions import (
    CorrelatedPairs,
    DAGRandomWalkToRoot,
    HierarchicalPairs,
    PowerLawDigraph,
    SimplicialComplexDistribution,
    SphericalDistribution,
    SparseUniform,
    TorusDistribution,
)

# --- Constants ---
N_FEAT = 6**4  # 1296 — 4th power for TorusDistribution(torus_dim=4)
N_SAMPLES = 200_000
DEVICE = "mps"
SAMPLE_CHUNK = 50_000

DIST_SEED = 42  # torch.Generator seed for all distributions
RANDOM_SEED = 42  # stdlib random seed for face/correlation generation

REPO_ID = (
    "kaushikreddyxyz/occhio-distributions"  # UPLOAD TO HUGGINGFACE AS A DATASET REPO
)
BRANDING = (
    "Generated by occhio — a research library for building and studying toy models. "
    "https://occhio.dev/ | Docs: https://docs.occhio.dev"
)

# --- Auth ---
HF_TOKEN = input("HuggingFace token: ")
api = HfApi(token=HF_TOKEN)
api.create_repo(REPO_ID, repo_type="dataset", exist_ok=True)


def zipfian_p_active(
    n: int, high: float = 0.2, low: float | None = None
) -> list[float]:
    """Zipfian (power-law) activation probabilities for n features."""
    if low is None:
        low = 0.5 / n
    alpha = math.log(high / low) / math.log(n)
    return [high / (i + 1) ** alpha for i in range(n)]


def upload_samples(
    name: str, dist, description: str, sample_chunk: int = SAMPLE_CHUNK
) -> None:
    """Sample from `dist` in chunks, save to safetensors, upload to HF."""
    print(f"\n{'=' * 60}")
    print(f"  {name} — sampling")
    print(f"{'=' * 60}")

    tmp = Path(tempfile.mkdtemp())
    try:
        # Sample in chunks; each chunk saved to CPU .pt to avoid MPS corruption
        samples_st = tmp / "samples.safetensors"
        chunk_paths = []
        remaining = N_SAMPLES
        i = 0
        while remaining > 0:
            chunk_size = min(sample_chunk, remaining)
            raw = dist.sample(chunk_size)
            samples_chunk = raw[0] if isinstance(raw, tuple) else raw
            cp = tmp / f"_chunk_{i}.pt"
            torch.save(samples_chunk.cpu(), cp)
            chunk_paths.append(cp)
            del samples_chunk, raw
            remaining -= chunk_size
            i += 1
            print(f"  sampled {N_SAMPLES - remaining}/{N_SAMPLES}")

        all_samples = torch.cat(
            [torch.load(cp, weights_only=True) for cp in chunk_paths]
        )
        for cp in chunk_paths:
            cp.unlink()

        # Sanity check
        nan_count = all_samples.isnan().sum().item()
        nonzero_rows = (all_samples.sum(dim=-1) != 0).sum().item()
        print(f"  NaN: {nan_count}, nonzero rows: {nonzero_rows}/{N_SAMPLES}")
        if nan_count > 0 or nonzero_rows == 0:
            print("  *** CORRUPT DATA — skipping upload ***")
            return

        # Write .safetensors
        save_file(
            {"samples": all_samples},
            str(samples_st),
            metadata={"class": type(dist).__name__},
        )

        # Write .json
        samples_json = {
            "occhio": BRANDING,
            "description": description,
            "n_samples": N_SAMPLES,
            "distribution_generator": {
                "seed": DIST_SEED,
                "device": DEVICE,
                "note": "torch.Generator seed used for distribution sampling",
            },
            "class": type(dist).__name__,
            "attributes": dist._collect_attrs(),
            "samples": {
                "shape": list(all_samples.shape),
                "dtype": str(all_samples.dtype),
                "n_samples": N_SAMPLES,
                "n_features": dist.n_features,
            },
        }
        (tmp / "samples.json").write_text(json.dumps(samples_json, indent=2) + "\n")
        del all_samples

        # Upload
        for suffix in (".safetensors", ".json"):
            local = tmp / f"samples{suffix}"
            remote = f"{name}/samples/samples{suffix}"
            api.upload_file(
                path_or_fileobj=str(local),
                path_in_repo=remote,
                repo_id=REPO_ID,
                repo_type="dataset",
            )
            print(f"  uploaded {remote}")
    finally:
        shutil.rmtree(tmp)

    print(f"  done: {name}\n")


