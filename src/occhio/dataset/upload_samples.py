# --- SimplicialComplexDistribution ---
FACE_DIM = 7
N_FACES = 4 * (N_FEAT // (FACE_DIM + 1))  # 648

dist_gen = torch.Generator(DEVICE)
dist_gen.manual_seed(DIST_SEED)
random.seed(RANDOM_SEED)

all_verts = list(range(N_FEAT))
random.shuffle(all_verts)
face_size = FACE_DIM + 1
covering_faces: set[tuple[int, ...]] = set()
for i in range(0, N_FEAT, face_size):
    chunk = all_verts[i : i + face_size]
    if len(chunk) < face_size:
        remaining = [v for v in all_verts if v not in chunk]
        chunk += random.sample(remaining, face_size - len(chunk))
    covering_faces.add(tuple(sorted(chunk)))
while len(covering_faces) < N_FACES:
    covering_faces.add(tuple(sorted(random.sample(range(N_FEAT), face_size))))
faces = list(covering_faces)[:N_FACES]

dist = SimplicialComplexDistribution(
    n_vertices=N_FEAT,
    faces=faces,
    sampling_mode="single",
    p_active=1 / N_FACES,
    device=DEVICE,
    generator=dist_gen,
)
upload_samples(
    "simplicial_complex",
    dist,
    description=(
        f"Simplicial complex distribution. Features are vertices of {FACE_DIM}-dimensional "
        f"simplices ({N_FACES} faces, {FACE_DIM + 1} vertices each). Faces are "
        "constructed to cover all vertices (stdlib random seed=42), then padded "
        "with random faces. Faces may share vertices ('gluing'). "
        "sampling_mode='single': one face fires per sample with "
        f"p_active=1/{N_FACES}. Models features living on geometric simplices — e.g. "
        "concepts like [Cold, Hot] or RGB color."
    ),
    sample_chunk=25_000,  # large intermediates on MPS; keep chunks small
)

